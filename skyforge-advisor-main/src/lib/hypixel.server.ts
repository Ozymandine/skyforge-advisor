let bazaarCache: { at: number; data: { lastUpdated: number; products: BazaarProduct[] } } | null =
  null;
const BAZAAR_CACHE_TTL = 60_000;

type BazaarResponse = {
  lastUpdated: number;

  products: Record<
    string,
    {
      quick_status: {
        productId: string;
        buyPrice: number;
        sellPrice: number;
        buyVolume: number;
        sellVolume: number;
        buyMovingWeek: number;
        sellMovingWeek: number;
        buyOrders: number;
        sellOrders: number;
      };
    }
  >;
};

// Share the raw feed between the market board and item detail pages.
let bazaarFeed: { fetchedAt: number; data: BazaarResponse } | undefined;
let bazaarRequest: Promise<BazaarResponse | null> | undefined;

function getBazaarFeed(): Promise<BazaarResponse | null> {
  if (bazaarFeed && Date.now() - bazaarFeed.fetchedAt < BAZAAR_CACHE_TTL) {
    return Promise.resolve(bazaarFeed.data);
  }
  bazaarRequest ??= getJson<BazaarResponse>(API + "/skyblock/bazaar")
    .then((result) => {
      const data = unwrap(result);
      if (!data?.products || !Number.isFinite(data.lastUpdated) || data.lastUpdated <= 0)
        return null;
      bazaarFeed = { fetchedAt: Date.now(), data };
      return data;
    })
    .finally(() => {
      bazaarRequest = undefined;
    });
  return bazaarRequest;
}

export async function getBazaar(): Promise<{
  lastUpdated: number;
  products: BazaarProduct[];
  stale?: boolean;
}> {
  // Short server cache: every client poll must NOT become a Hypixel fetch.
  const now = Date.now();
  if (bazaarCache && now - bazaarCache.at < BAZAAR_CACHE_TTL) {
    return bazaarCache.data;
  }
  try {
    const [data, names] = await Promise.all([getBazaarFeed(), nameLookup()]);
    if (!data || !data.products) {
      // Distinguish failure (stale) from truly empty — never fake lastUpdated.
      if (bazaarCache) return { ...bazaarCache.data, stale: true };
      return {
        lastUpdated: 0,
        products: [],
        stale: true,
      };
    }

    const products: BazaarProduct[] = [];

    for (const [id, entry] of Object.entries(data.products)) {
      const q = entry.quick_status;

      if (
        !q ||
        !Number.isFinite(q.buyPrice) ||
        !Number.isFinite(q.sellPrice) ||
        ![q.buyVolume, q.sellVolume, q.buyMovingWeek, q.sellMovingWeek].every(
          (value) => Number.isFinite(value) && value >= 0,
        ) ||
        q.buyPrice <= 0 ||
        q.sellPrice <= 0
      ) {
        continue;
      }

      const gross = q.buyPrice - q.sellPrice;

      const spread = gross - q.buyPrice * 0.0125;

      const margin = (spread / q.sellPrice) * 100;

      products.push({
        id,

        name: names.get(id) ?? titleCase(id.replace(/^ENCHANTED_/, "Enchanted ")),

        buyPrice: q.buyPrice,
        sellPrice: q.sellPrice,
        spread,
        margin,

        buyVolume: q.buyVolume,
        sellVolume: q.sellVolume,

        buyMovingWeek: q.buyMovingWeek,

        sellMovingWeek: q.sellMovingWeek,
      });
    }

    products.sort(
      (a, b) => b.buyMovingWeek + b.sellMovingWeek - a.buyMovingWeek - a.sellMovingWeek,
    );

    const fresh = {
      lastUpdated: data.lastUpdated ?? 0,
      products,
    };
    bazaarCache = { at: Date.now(), data: fresh };
    return fresh;
  } catch (err) {
    console.error("Error in getBazaar:", err);

    if (bazaarCache) return { ...bazaarCache.data, stale: true };
    return {
      lastUpdated: 0,
      products: [],
      stale: true,
    };
  }
}

