function pruneCache<K, V>(cache: Map<K, V>, max: number): void {
  if (cache.size <= max) return;
  // Evict oldest-inserted entries first (Maps preserve insertion order).
  for (const key of cache.keys()) {
    cache.delete(key);
    if (cache.size <= max) break;
  }
}

