type BazaarResponse = {
  lastUpdated: number;

  products: Record<
    string,
    {
      quick_status: {
        productId: string;
        buyPrice: number;
        sellPrice: number;
        buyVolume: number;
        sellVolume: number;
        buyMovingWeek: number;
        sellMovingWeek: number;
        buyOrders: number;
        sellOrders: number;
      };
    }
  >;
};

export async function getBazaar(): Promise<{
  lastUpdated: number;
  products: BazaarProduct[];
}> {
  try {
    const [data, names] = await Promise.all([
      getJson<BazaarResponse>(`${API}/skyblock/bazaar`),
      nameLookup(),
    ]);

    if (!data || !data.products) {
      return {
        lastUpdated: Date.now(),
        products: [],
      };
    }

    const products: BazaarProduct[] = [];

    for (const [id, entry] of Object.entries(data.products)) {
      const q = entry.quick_status;

      if (
        !q ||
        !Number.isFinite(q.buyPrice) ||
        !Number.isFinite(q.sellPrice) ||
        q.buyPrice <= 0 ||
        q.sellPrice <= 0
      ) {
        continue;
      }

      const gross = q.buyPrice - q.sellPrice;

      const spread = gross - q.buyPrice * 0.0125;

      if (spread <= 0) {
        continue;
      }

      const flipsPerHour = Math.min(q.buyMovingWeek, q.sellMovingWeek) / 168;

      const liquidity = Math.min(100, Math.round(Math.log10(Math.max(1, flipsPerHour)) * 25));

      const margin = (spread / q.sellPrice) * 100;

      products.push({
        id,

        name: names.get(id) ?? titleCase(id.replace(/^ENCHANTED_/, "Enchanted ")),

        buyPrice: q.buyPrice,
        sellPrice: q.sellPrice,
        spread,
        margin,

        buyVolume: q.buyVolume,
        sellVolume: q.sellVolume,

        buyMovingWeek: q.buyMovingWeek,

        sellMovingWeek: q.sellMovingWeek,

        profitPerHour: spread * flipsPerHour,

        liquidity,

        health: Math.min(100, Math.round(liquidity * 0.6 + Math.min(margin, 60) * 0.7)),
      });
    }

    products.sort((a, b) => b.profitPerHour - a.profitPerHour);

    return {
      lastUpdated: data.lastUpdated || Date.now(),
      products,
    };
  } catch (err) {
    console.error("Error in getBazaar:", err);

    return {
      lastUpdated: Date.now(),
      products: [],
    };
  }
}

