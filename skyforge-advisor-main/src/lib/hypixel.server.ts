function stripColors(value: string): string {
  return value.replace(/§./g, "");
}

function rarityFromLore(lore: string[]): string {
  for (let i = lore.length - 1; i >= 0; i--) {
    const line = stripColors(lore[i] ?? "").toUpperCase();

    const hit = RARITY_WORDS.find((rarity) => line.includes(rarity));

    if (hit) {
      return hit.replace(" ", "_");
    }
  }

  return "COMMON";
}

