/**
 * Full encyclopedia payload for one item: the merged item record plus
 * NEU extras (crafting grid, canonical wiki URL, craft text) and a
 * reverse "used to craft" index built from all known recipes.
 */
export async function getItemEncyclopedia(itemId: string): Promise<{
  item: WikiItem | null;
  extra: ItemExtra | null;
  usedIn: Array<{ id: string; name: string; amount: number }>;
}> {
  const normalized = itemId.trim().toUpperCase();
  if (!normalized) {
    return { item: null, extra: null, usedIn: [] };
  }

  const [items, recipes] = await Promise.all([getWikiItems(), getRecipeIndex()]);

  const item = items.find((entry) => entry.id.toUpperCase() === normalized) ?? null;

  const extra = ITEM_EXTRAS[normalized] ?? null;

  const names = new Map(items.map((entry) => [entry.id, entry.name]));

  const usedIn = (recipes.get(normalized) ?? [])
    .map(({ id, amount }) => ({
      id,
      amount,
      name: names.get(id) ?? titleCase(id),
    }))
    .sort((a, b) => b.amount - a.amount || a.name.localeCompare(b.name));

  return { item, extra, usedIn };
}

/** Internal ID -> list of recipes that consume it (reverse crafting index). */
async function getRecipeIndex(): Promise<Map<string, Array<{ id: string; amount: number }>>> {
  const items = await getItems();
  const index = new Map<string, Array<{ id: string; amount: number }>>();

  for (const item of items) {
    if (!item.recipe) continue;
    for (const ingredient of item.recipe.ingredients) {
      const list = index.get(ingredient.id.toUpperCase()) ?? [];
      list.push({ id: item.id, amount: ingredient.amount });
      index.set(ingredient.id.toUpperCase(), list);
    }
  }

  return index;
}

