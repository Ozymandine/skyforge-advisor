function cleanText(value: unknown): string {
  if (typeof value !== "string") {
    return "";
  }

  return value.replace(/§./g, "").trim();
}

function normalizeDescription(value: string | string[] | undefined): string | string[] | undefined {
  if (typeof value === "string") {
    const cleaned = cleanText(value);
    return cleaned || undefined;
  }

  if (Array.isArray(value)) {
    const lines = value.map((line) => cleanText(line)).filter(Boolean);

    return lines.length ? lines : undefined;
  }

  return undefined;
}

function normalizeRequirements(
  requirements: RawRequirement[] | undefined,
): WikiRequirement[] | undefined {
  if (!Array.isArray(requirements)) {
    return undefined;
  }

  const normalized = requirements
    .map((req) => {
      if (!req || typeof req !== "object") {
        return null;
      }

      const type =
        typeof req.type === "string" ? titleCase(req.type.replace(/_/g, " ")) : "Requirement";

      const level = typeof req.level === "number" ? req.level : undefined;

      const value = typeof req.value === "string" ? req.value : undefined;

      return {
        type,
        ...(level !== undefined ? { level } : {}),
        ...(value !== undefined ? { value } : {}),
      };
    })
    .filter((req): req is WikiRequirement => req !== null);

  return normalized.length ? normalized : undefined;
}

function normalizeAbilities(abilities: RawAbility[] | undefined): WikiAbility[] | undefined {
  if (!Array.isArray(abilities)) {
    return undefined;
  }

  const normalized = abilities
    .filter((ability): ability is RawAbility => !!ability && typeof ability === "object")
    .map((ability) => ({
      name: cleanText(ability.name) || "Ability",

      description:
        typeof ability.description === "string"
          ? cleanText(ability.description)
          : Array.isArray(ability.description)
            ? ability.description.map(cleanText).filter(Boolean)
            : "",

      ...(typeof ability.mana_cost === "number" ? { manaCost: ability.mana_cost } : {}),

      ...(typeof ability.cooldown === "number" ? { cooldown: ability.cooldown } : {}),
    }));

  return normalized.length ? normalized : undefined;
}

// The Hypixel resource response contains recipe information on some items.
// Its exact structure has changed over time, so normalize the common forms
// without assuming every item has a recipe.
function normalizeRecipe(recipe: RawRecipe | undefined): WikiRecipe | undefined {
  if (!recipe || typeof recipe !== "object") {
    return undefined;
  }

  const ingredients: Array<{
    id: string;
    name: string;
    amount: number;
  }> = [];

  const pushIngredient = (id: string, amount: number) => {
    if (!id || !Number.isFinite(amount) || amount <= 0) {
      return;
    }

    ingredients.push({
      id,
      name: titleCase(id),
      amount,
    });
  };

  const rawIngredients = recipe["ingredients"];

  if (Array.isArray(rawIngredients)) {
    for (const ingredient of rawIngredients) {
      if (!ingredient || typeof ingredient !== "object") {
        continue;
      }

      const obj = ingredient as Record<string, unknown>;

      const id =
        typeof obj["id"] === "string"
          ? obj["id"]
          : typeof obj["item_id"] === "string"
            ? obj["item_id"]
            : undefined;

      const amount =
        typeof obj["amount"] === "number"
          ? obj["amount"]
          : typeof obj["count"] === "number"
            ? obj["count"]
            : 1;

      if (id) {
        pushIngredient(id, amount);
      }
    }
  }

  // Some Hypixel recipe structures use a simple ID -> quantity map.
  if (rawIngredients && typeof rawIngredients === "object" && !Array.isArray(rawIngredients)) {
    for (const [id, amount] of Object.entries(rawIngredients as Record<string, unknown>)) {
      if (typeof amount === "number") {
        pushIngredient(id, amount);
      }
    }
  }

  if (!ingredients.length) {
    return undefined;
  }

  const craftingType =
    typeof recipe["crafting_type"] === "string"
      ? titleCase(String(recipe["crafting_type"]))
      : typeof recipe["type"] === "string"
        ? titleCase(String(recipe["type"]))
        : undefined;

  const outputAmount =
    typeof recipe["output_amount"] === "number"
      ? recipe["output_amount"]
      : typeof recipe["count"] === "number"
        ? recipe["count"]
        : undefined;

  return {
    ingredients,
    ...(craftingType ? { craftingType } : {}),
    ...(outputAmount !== undefined ? { outputAmount } : {}),
  };
}

export async function getItems(): Promise<WikiItem[]> {
  try {
    if (itemsCache && Date.now() - itemsCache.at < 30 * 60_000) {
      return itemsCache.items;
    }

    const data = unwrap(await getJson<ItemsResponse>(`${API}/resources/skyblock/items`));

    if (!data || !Array.isArray(data.items)) {
      // Keep stale good value instead of flashing empty wiki on failure.
      return itemsCache?.items ?? [];
    }

    const items: WikiItem[] = data.items.map((item) => {
      const extra = ITEM_EXTRAS[item.id];

      const description =
        normalizeDescription(typeof item.description === "string" ? item.description : item.lore) ??
        (Array.isArray(extra?.lore) && extra.lore.length
          ? normalizeDescription(extra.lore)
          : undefined);

      const stats =
        item.stats && typeof item.stats === "object" && Object.keys(item.stats).length > 0
          ? (item.stats as Record<string, number>)
          : extra?.stats;

      const abilities =
        normalizeAbilities(item.abilities) ??
        (extra?.abilities?.length
          ? extra.abilities.map((ability) => ({
              name: ability.name,
              description: ability.desc,
              ...(ability.manaCost != null
                ? {
                    manaCost: ability.manaCost,
                  }
                : {}),
              ...(ability.cooldown != null
                ? {
                    cooldown: ability.cooldown,
                  }
                : {}),
            }))
          : undefined);

      const requirements =
        normalizeRequirements(item.requirements) ??
        (extra?.requirements?.length ? extra.requirements : undefined);

      const recipe =
        normalizeRecipe(item.recipe) ??
        normalizeRecipe(
          (generatedRecipes as Record<string, unknown>)[item.id] !== undefined
            ? {
                ingredients: (generatedRecipes as Record<string, { id: string; amount: number }[]>)[
                  item.id
                ],
              }
            : undefined,
        );

      return {
        id: item.id,
        name: (item.name ?? titleCase(item.id)).replace(/§./g, "").trim(),

        ...(item.material !== undefined ? { material: item.material } : {}),
        rarity: item.tier ?? "COMMON",
        category: item.category ? titleCase(item.category) : "Misc",

        npcSell: typeof item.npc_sell_price === "number" ? item.npc_sell_price : null,

        ...(description !== undefined ? { description } : {}),

        ...(Array.isArray(extra?.lore) && extra.lore.length
          ? {
              lore: extra.lore.map((line) =>
                line.replace(/§./g, "").replace(/[\uDC00-\uDFFF\uE000-\uF8FF]/g, ""),
              ),
            }
          : {}),

        ...(stats ? { stats } : {}),

        ...(abilities ? { abilities } : {}),

        ...(requirements ? { requirements } : {}),

        ...(recipe ? { recipe } : {}),

        ...(extra?.wikiUrl ? { wikiUrl: extra.wikiUrl } : {}),
      };
    });

    itemsCache = {
      at: Date.now(),
      items,
    };

    return items;
  } catch (err) {
    console.error("Error inside getItems:", err);
    return [];
  }
}

async function nameLookup(): Promise<Map<string, string>> {
  try {
    const items = await getItems();

    return new Map(items.map((item) => [item.id, item.name]));
  } catch {
    return new Map();
  }
}

