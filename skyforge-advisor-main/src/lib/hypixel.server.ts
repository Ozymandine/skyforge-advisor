async function parseContainer(
  base64: string | undefined,
  id: string,
  label: string,
): Promise<InventoryContainer | null> {
  if (!base64) {
    return null;
  }

  try {
    const root = await decodeNbt(base64);

    const list = root["i"];
    if (!Array.isArray(list)) throw new Error("Inventory item list is missing");

    const items: InventoryItem[] = [];

    list.forEach((entry, index) => {
      const it = nbtObject(entry);

      if (!it) throw new Error("Invalid inventory slot");

      const tag = nbtObject(it["tag"]) ?? {};

      const display = nbtObject(tag["display"]) ?? {};

      const extra = nbtObject(tag["ExtraAttributes"]) ?? {};

      // Empty slots have no item id — skip them entirely.
      const itemId = extra["id"];
      if (typeof itemId !== "string" || !itemId) {
        return;
      }

      const lore = nbtArray(display["Lore"]).map((line) => stripColors(String(line)));

      const rawName = display["Name"] ?? extra["id"] ?? "Unknown Item";

      const name = stripColors(String(rawName));

      const texture = textureFromTag(tag);
      const rawCount = it["Count"];

      const count = typeof rawCount === "number" ? rawCount : Number(rawCount ?? 1);

      // NBT ExtraAttributes: enchantments, reforge, gems, stars, HPBs.
      const enchantmentsRaw = nbtObject(extra["enchantments"]);
      const enchantments: Record<string, number> = {};
      for (const [ench, level] of Object.entries(enchantmentsRaw ?? {})) {
        const num = Number(level);
        if (Number.isFinite(num) && num > 0) enchantments[ench] = num;
      }

      const reforgeRaw = extra["modifier"];
      const gemsRaw = nbtObject(extra["gems"]);
      const gems: Record<string, string> = {};
      for (const [slot, gem] of Object.entries(gemsRaw ?? {})) {
        if (typeof gem === "string" && gem && !/_gem$/.test(slot)) {
          gems[slot] = gem;
        }
      }

      const starsRaw = extra["dungeon_item_level"] ?? extra["upgrade_level"];
      const hpbRaw = extra["hot_potato_count"];
      const rarityUpgrades = extra["rarity_upgrades"];
      const instanceId = extra["uuid"];

      const scrollsRaw = nbtArray(extra["ability_scroll"]);

      const attributesRaw = nbtObject(extra["attributes"]);
      const attributes: Record<string, number> = {};
      for (const [attrKey, attrLvl] of Object.entries(attributesRaw ?? {})) {
        const num = Number(attrLvl);
        if (Number.isFinite(num) && num > 0) attributes[attrKey] = num;
      }

      const artOfWarRaw = extra["art_of_war_count"];
      const woodSingularityRaw = extra["wood_singularity_count"];

      items.push({
        slot: index,

        name,

        id: itemId,
        ...(typeof instanceId === "string" && instanceId ? { instanceId } : {}),

        ...(texture ? { texture } : {}),

        rarity: rarityFromLore(lore),

        count: Number.isFinite(count) ? count : 1,

        lore,

        ...(Object.keys(enchantments).length > 0 ? { enchantments } : {}),

        ...(typeof reforgeRaw === "string" && reforgeRaw
          ? { reforge: titleCase(reforgeRaw.replace(/_/g, " ")) }
          : {}),

        ...(typeof starsRaw === "number" && starsRaw > 0 ? { stars: starsRaw } : {}),
        ...(typeof rarityUpgrades === "number" && rarityUpgrades > 0 ? { rarityUpgrades } : {}),

        ...(typeof hpbRaw === "number" && hpbRaw > 0 ? { hotPotatoBooks: hpbRaw } : {}),

        ...(Object.keys(gems).length > 0 ? { gems } : {}),

        ...(scrollsRaw.length > 0
          ? {
              abilityScrolls: scrollsRaw
                .map((s) => titleCase(String(s).replace(/_/g, " ")))
                .slice(0, 3),
            }
          : {}),

        ...(Object.keys(attributes).length > 0 ? { attributes } : {}),

        ...(typeof artOfWarRaw === "number" && artOfWarRaw > 0 ? { artOfWar: artOfWarRaw } : {}),

        ...(typeof woodSingularityRaw === "number" && woodSingularityRaw > 0
          ? { woodSingularity: woodSingularityRaw }
          : {}),
      });
    });

    return {
      id,
      label,

      slots: Math.max(list.length, items.length),

      items,
    };
  } catch {
    return {
      id,
      label,
      slots: 0,
      items: [],
      locked: true,
    };
  }
}

