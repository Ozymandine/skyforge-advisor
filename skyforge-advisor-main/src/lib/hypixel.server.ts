type AuctionsResponse = {
  page: number;
  totalPages: number;
  totalAuctions: number;
  lastUpdated: number;

  auctions: Array<{
    uuid: string;

    item_bytes?:
      | string
      | {
          type?: number;
          data?: string;
        };

    item_id?: string;
    item_name: string;
    tier: string;
    bin: boolean;
    starting_bid: number;
    highest_bid_amount: number;
    end: number;
    bids: unknown[];
    category: string;
    item_lore: string;
  }>;
};

type AuctionItemIdentity = Pick<AuctionEntry, "id" | "texture">;

type AuctionCandidate = {
  entry: AuctionEntry;
  uuid: string;
  itemBytes: AuctionsResponse["auctions"][number]["item_bytes"];
};

const auctionItemCache = new Map<
  string,
  {
    at: number;
    identity: AuctionItemIdentity;
  }
>();

const AUCTION_ITEM_CACHE_TTL_MS = 15 * 60_000;

const AUCTION_ICON_LIMIT = 240;
const AUCTION_ITEM_DECODE_CONCURRENCY = 8;

function itemBytesData(
  itemBytes: AuctionsResponse["auctions"][number]["item_bytes"],
): string | undefined {
  if (typeof itemBytes === "string") {
    return itemBytes;
  }

  if (typeof itemBytes?.data === "string") {
    return itemBytes.data;
  }

  return undefined;
}

function nbtObject(value: NbtValue | undefined): Record<string, NbtValue> | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return null;
  }

  const object = value as Record<string, NbtValue>;

  const wrapped = object["value"];

  if (wrapped && typeof wrapped === "object" && !Array.isArray(wrapped)) {
    return wrapped as Record<string, NbtValue>;
  }

  return object;
}

function nbtArray(value: NbtValue | undefined): NbtValue[] {
  if (Array.isArray(value)) {
    return value;
  }

  const object = nbtObject(value);
  const wrapped = object?.["value"];

  return Array.isArray(wrapped) ? wrapped : [];
}

function textureFromTag(tag: Record<string, NbtValue>): string | undefined {
  const skullOwner = nbtObject(tag["SkullOwner"]);

  const properties = nbtObject(skullOwner?.["Properties"]);

  const textures = nbtArray(properties?.["textures"]);

  const firstTexture = nbtObject(textures[0]);

  const value = firstTexture?.["Value"] ?? firstTexture?.["value"];

  if (typeof value !== "string" || !value) {
    return undefined;
  }

  try {
    const decoded = JSON.parse(Buffer.from(value, "base64").toString("utf8")) as {
      textures?: {
        SKIN?: {
          url?: string;
        };
      };
    };

    return decoded.textures?.SKIN?.url?.replace(/^http:/, "https:");
  } catch {
    return value.startsWith("http")
      ? value.replace(/^http:/, "https:")
      : `https://textures.minecraft.net/texture/${value}`;
  }
}

async function extractAuctionItemIdentity(
  itemBytes: AuctionsResponse["auctions"][number]["item_bytes"],
): Promise<AuctionItemIdentity> {
  const data = itemBytesData(itemBytes);

  if (!data) {
    return {};
  }

  try {
    const root = await decodeNbt(data);

    const itemStack = nbtObject(nbtArray(root["i"])[0]);

    const tag = nbtObject(itemStack?.["tag"]);

    const extra = nbtObject(tag?.["ExtraAttributes"]);

    const id = extra?.["id"];

    const texture = tag ? textureFromTag(tag) : undefined;

    return {
      ...(typeof id === "string" && id ? { id } : {}),

      ...(texture ? { texture } : {}),
    };
  } catch {
    return {};
  }
}

function pruneAuctionItemCache(now: number) {
  for (const [uuid, cached] of auctionItemCache) {
    if (now - cached.at > AUCTION_ITEM_CACHE_TTL_MS) {
      auctionItemCache.delete(uuid);
    }
  }
}

async function auctionItemIdentity(
  uuid: string,
  itemBytes: AuctionsResponse["auctions"][number]["item_bytes"],
): Promise<AuctionItemIdentity> {
  const now = Date.now();

  const cached = auctionItemCache.get(uuid);

  if (cached && now - cached.at <= AUCTION_ITEM_CACHE_TTL_MS) {
    return cached.identity;
  }

  const identity = await extractAuctionItemIdentity(itemBytes);

  auctionItemCache.set(uuid, {
    at: now,
    identity,
  });

  return identity;
}

async function hydrateAuctionEntries(candidates: AuctionCandidate[]): Promise<AuctionEntry[]> {
  const entries = candidates.map(({ entry }) => entry);

  let next = 0;

  const worker = async () => {
    for (;;) {
      const index = next++;
      const candidate = candidates[index];

      if (!candidate) {
        return;
      }

      const identity = await auctionItemIdentity(candidate.uuid, candidate.itemBytes);

      const id = candidate.entry.id ?? identity.id;

      entries[index] = {
        ...candidate.entry,

        ...(id ? { id } : {}),

        ...(identity.texture
          ? {
              texture: identity.texture,
            }
          : {}),
      };
    }
  };

  await Promise.all(
    Array.from(
      {
        length: Math.min(AUCTION_ITEM_DECODE_CONCURRENCY, candidates.length),
      },
      worker,
    ),
  );

  return entries;
}

// Shared auction scan cache: one 24-page scan serves every visitor for the
// TTL window instead of re-fetching Hypixel per request.
const auctionScanCache = new Map<
  number,
  { at: number; data: Awaited<ReturnType<typeof getAuctions>> }
>();
const AUCTION_CACHE_TTL = 3 * 60_000;

export async function getAuctions(pages = 6): Promise<{
  lastUpdated: number;
  totalAuctions: number;
  totalPages: number;
  binCount: number;
  auctionCount: number;
  uniqueItems: number;
  averageBin: number;
  entries: AuctionEntry[];
}> {
  const cached = auctionScanCache.get(pages);
  if (cached && Date.now() - cached.at < AUCTION_CACHE_TTL) {
    return cached.data;
  }

  const fallback = {
    lastUpdated: Date.now(),
    totalAuctions: 0,
    totalPages: 0,
    binCount: 0,
    auctionCount: 0,
    uniqueItems: 0,
    averageBin: 0,
    entries: [] as AuctionEntry[],
  };

  try {
    const first = await getJson<AuctionsResponse>(`${API}/skyblock/auctions?page=0`);

    if (!first || !Array.isArray(first.auctions)) {
      return fallback;
    }

    const wanted = Math.min(Math.max(1, pages), first.totalPages || 1);

    const rest = await Promise.all(
      Array.from(
        {
          length: Math.max(0, wanted - 1),
        },
        (_, i) =>
          getJson<AuctionsResponse>(`${API}/skyblock/auctions?page=${i + 1}`).catch(() => null),
      ),
    );

    const all = [
      first,
      ...rest.filter(
        (value): value is AuctionsResponse => value !== null && Array.isArray(value.auctions),
      ),
    ];

    const raw = all.flatMap((page) => page.auctions);

    const lowestBin = new Map<string, number>();

    let binCount = 0;
    let binTotal = 0;

    for (const auction of raw) {
      if (!auction.bin) {
        continue;
      }

      binCount += 1;
      binTotal += auction.starting_bid;

      const key = `${auction.item_name}|${auction.tier}`;

      const previous = lowestBin.get(key);

      if (previous === undefined || auction.starting_bid < previous) {
        lowestBin.set(key, auction.starting_bid);
      }
    }

    const now = Date.now();

    pruneAuctionItemCache(now);

    const candidates: AuctionCandidate[] = raw.map((auction) => {
      const key = `${auction.item_name}|${auction.tier}`;

      const price = auction.bin
        ? auction.starting_bid
        : Math.max(auction.highest_bid_amount, auction.starting_bid);

      const lb = lowestBin.get(key) ?? null;

      return {
        uuid: auction.uuid,

        itemBytes: auction.item_bytes,

        entry: {
          uuid: auction.uuid,

          ...(auction.item_id
            ? {
                id: auction.item_id,
              }
            : {}),

          name: auction.item_name,

          rarity: auction.tier,

          bin: auction.bin,

          price,

          topBid: auction.bin ? null : Math.max(auction.highest_bid_amount, 0) || null,

          lowestBin: lb,

          profit: lb !== null ? lb - price : 0,

          endsInMs: auction.end - now,

          bids: Array.isArray(auction.bids) ? auction.bids.length : 0,

          category: auction.category ? titleCase(auction.category) : "Misc",
        },
      };
    });

    const entries = await hydrateAuctionEntries(
      candidates
        .sort((a, b) => b.entry.profit - a.entry.profit || b.entry.price - a.entry.price)
        .slice(0, AUCTION_ICON_LIMIT),
    );

    const result = {
      lastUpdated: first.lastUpdated || now,

      totalAuctions: first.totalAuctions || raw.length,

      totalPages: first.totalPages || 1,

      binCount,

      auctionCount: raw.length - binCount,

      uniqueItems: lowestBin.size,

      averageBin: binCount ? binTotal / binCount : 0,

      entries,
    };

    // Only cache successful, non-empty scans so a bad response never sticks.
    if (entries.length > 0) {
      auctionScanCache.set(pages, { at: Date.now(), data: result });
    }

    return result;
  } catch (err) {
    console.error("Error in getAuctions:", err);

    return fallback;
  }
}

