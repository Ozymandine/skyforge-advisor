export async function resolveUuid(
  username: string,
): Promise<{ uuid: string; name: string } | null> {
  try {
    const clean = username.trim().replace(/-/g, "");

    if (/^[0-9a-f]{32}$/i.test(clean)) {
      return {
        uuid: clean,
        name: username,
      };
    }

    // UUIDs never change — cache forever.
    const cached = uuidCache.get(username.trim().toLowerCase());
    if (cached) return cached;

    const res = await fetch(
      `https://api.mojang.com/users/profiles/minecraft/${encodeURIComponent(username.trim())}`,
    );

    if (res.ok) {
      const data = (await res.json()) as {
        id: string;
        name: string;
      };

      if (data?.id) {
        const resolved = {
          uuid: data.id,
          name: data.name,
        };
        uuidCache.set(username.trim().toLowerCase(), resolved);
        return resolved;
      }
    }

    const fallback = await fetch(
      `https://playerdb.co/api/player/minecraft/${encodeURIComponent(username.trim())}`,
    );

    if (fallback.ok) {
      const data = (await fallback.json()) as {
        data?: {
          player?: {
            raw_id?: string;
            username?: string;
          };
        };
      };

      const raw = data?.data?.player?.raw_id;

      if (raw) {
        const resolved = {
          uuid: raw,
          name: data.data?.player?.username ?? username,
        };
        uuidCache.set(username.trim().toLowerCase(), resolved);
        return resolved;
      }
    }
  } catch (err) {
    console.error("Failed to resolve UUID:", err);
  }

  return null;
}

