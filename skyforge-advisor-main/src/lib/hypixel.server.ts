export async function getWikiItems(): Promise<WikiItem[]> {
  const [items, bazaarResponse] = await Promise.all([getItems(), getBazaarFeed()]);

  const bazaarMap = new Map<string, WikiMarketData["bazaar"]>();

  if (bazaarResponse?.products) {
    for (const [id, entry] of Object.entries(bazaarResponse.products)) {
      const q = entry.quick_status;

      if (
        !q ||
        !Number.isFinite(q.buyPrice) ||
        !Number.isFinite(q.sellPrice) ||
        q.buyPrice <= 0 ||
        q.sellPrice <= 0
      ) {
        continue;
      }

      bazaarMap.set(id, {
        buyPrice: q.buyPrice,
        sellPrice: q.sellPrice,
        buyVolume: q.buyVolume,
        sellVolume: q.sellVolume,
        buyMovingWeek: q.buyMovingWeek,
        sellMovingWeek: q.sellMovingWeek,
        buyOrders: q.buyOrders,
        sellOrders: q.sellOrders,
      });
    }
  }

  return items.map((item) => {
    const bazaar = bazaarMap.get(item.id);

    const demand = bazaar
      ? Math.min(
          100,
          Math.round(Math.log10(Math.max(1, bazaar.buyMovingWeek + bazaar.sellMovingWeek)) * 20),
        )
      : null;

    const volume = bazaar ? bazaar.buyMovingWeek + bazaar.sellMovingWeek : null;

    return {
      ...item,

      ...(bazaar && bazaarResponse ? { bazaar, bazaarUpdatedAt: bazaarResponse.lastUpdated } : {}),

      // Hypixel's public item API does not provide
      // a true historical price series. Keep this
      // null rather than inventing historical data.
      historicalPrice: null,

      ...(demand !== null ? { demand } : {}),

      ...(volume !== null ? { volume } : {}),
    };
  });
}

